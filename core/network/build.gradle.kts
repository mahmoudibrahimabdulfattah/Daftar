// Test-only fixtures: the captured HTML files are turned into Kotlin string constants at build time, so the
// same bytes reach the Android host test and the iOS simulator test without a JVM-only resource loader.
val fixtureSourceDir = layout.projectDirectory.dir("src/commonTest/resources/fixtures")
val generatedFixtureDir = layout.buildDirectory.dir("generated/fixtures/commonTest/kotlin")

val generateTestFixtures = tasks.register("generateTestFixtures") {
    val sourceDir = fixtureSourceDir.asFile
    val outputDir = generatedFixtureDir.get().asFile
    val chunkChars = 8_000
    inputs.dir(sourceDir)
    outputs.dir(outputDir)
    doLast {
        fun kotlinLiteral(text: String): String = buildString {
            text.forEach { ch ->
                when {
                    ch == '\\' -> append("\\\\")
                    ch == '"' -> append("\\\"")
                    ch == '$' -> append("\\$")
                    ch == '\n' -> append("\\n")
                    ch == '\r' -> append("\\r")
                    ch == '\t' -> append("\\t")
                    ch.code < 0x20 || ch.code > 0x7E -> append("\\u%04x".format(ch.code))
                    else -> append(ch)
                }
            }
        }

        val fixtures = mapOf(
            "isaghaPricesHtml" to "isagha-prices.html",
            "isaghaFxHtml" to "isagha-fx.html",
        )
        val packageDir = File(outputDir, "com/mk/daftar/core/network/fixtures").apply { mkdirs() }
        val body = buildString {
            appendLine("// Generated by generateTestFixtures from src/commonTest/resources/fixtures. Do not edit.")
            appendLine("package com.mk.daftar.core.network.fixtures")
            appendLine()
            appendLine("internal object TestFixtures {")
            fixtures.forEach { (name, file) ->
                val text = File(sourceDir, file).readText(Charsets.UTF_8)
                appendLine("    val $name: String by lazy {")
                appendLine("        buildString {")
                text.chunked(chunkChars).forEach { chunk ->
                    appendLine("            append(\"${kotlinLiteral(chunk)}\")")
                }
                appendLine("        }")
                appendLine("    }")
                appendLine()
            }
            appendLine("}")
        }
        File(packageDir, "TestFixtures.kt").writeText(body, Charsets.UTF_8)
    }
}

// Registering the task itself as a source directory gives every test compilation (JVM and native) the dependency.
kotlin.sourceSets.getByName("commonTest").kotlin.srcDir(generateTestFixtures)

// Lint (model and analysis) reads the generated test sources, so it runs after the fixture generator. Declared
// explicitly: the source-directory link above is not seen as a dependency by Gradle's lint tasks.
tasks.matching { it.name.contains("lint", ignoreCase = true) && it.name.contains("HostTest") }.configureEach {
    dependsOn(generateTestFixtures)
}

